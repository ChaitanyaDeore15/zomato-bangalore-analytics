"""
Main Streamlit Analytics Dashboard Application
Interactive web visualization dashboard for Zomato Bangalore Restaurant Analytics.
"""

import sys
from pathlib import Path

# Add project root to sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import streamlit as st
import pandas as pd
import json

from src.config import (
    CLEANED_DATASET_CSV,
    ANALYSIS_RESULTS_DIR
)
from dashboard.components import (
    render_header,
    render_metrics_cards,
    render_locality_chart,
    render_cuisine_matrix_chart,
    render_cost_rating_scatter,
    render_rating_distribution_chart
)

# Page Setup
st.set_page_config(
    page_title="Zomato Analytics | Apache Spark & Big Data Visualization",
    page_icon="🍽️",
    layout="wide",
    initial_sidebar_state="expanded"
)


@st.cache_data
def load_clean_dataset() -> pd.DataFrame:
    """Loads preprocessed dataset generated by Apache Spark pipeline."""
    if not CLEANED_DATASET_CSV.exists():
        st.error(f"Cleaned dataset not found at {CLEANED_DATASET_CSV}. Please run 'python src/export_results.py' first.")
        st.stop()
    return pd.read_csv(CLEANED_DATASET_CSV)


@st.cache_data
def load_analysis_csv(filename: str) -> pd.DataFrame:
    """Loads pre-aggregated Spark analytical results."""
    path = ANALYSIS_RESULTS_DIR / filename
    if not path.exists():
        return pd.DataFrame()
    return pd.read_csv(path)


# Load Data
df = load_clean_dataset()
quality_df = load_analysis_csv("data_quality_report.csv")
locality_agg = load_analysis_csv("locality_summary.csv")
cuisine_agg = load_analysis_csv("cuisine_popularity.csv")
cuisine_rated_agg = load_analysis_csv("cuisine_ratings_thresholded.csv")
matrix_agg = load_analysis_csv("locality_cuisine_matrix.csv")
if not matrix_agg.empty and "location" in matrix_agg.columns:
    matrix_agg = matrix_agg.set_index("location")

# Sidebar Filter Controls
st.sidebar.header("🔍 Interactive Data Filters")

# Locality Filter
all_localities = sorted([str(x) for x in df["location"].dropna().unique()])
selected_localities = st.sidebar.multiselect(
    "Bangalore Locality",
    options=all_localities,
    default=[]
)

# Online Order Filter
online_option = st.sidebar.radio(
    "Online Ordering Available?",
    options=["All", "Yes", "No"],
    index=0
)

# Table Booking Filter
table_option = st.sidebar.radio(
    "Table Booking Available?",
    options=["All", "Yes", "No"],
    index=0
)

# Rating Slider
min_rating, max_rating = st.sidebar.slider(
    "Rating Range",
    min_value=1.0,
    max_value=5.0,
    value=(1.0, 5.0),
    step=0.1
)

# Cost Slider
max_cost_data = int(df["approx_cost_num"].dropna().max()) if not df["approx_cost_num"].dropna().empty else 3000
cost_range = st.sidebar.slider(
    "Cost for Two Range (₹)",
    min_value=50,
    max_value=max_cost_data,
    value=(50, max_cost_data),
    step=50
)

# Filter Application Logic
filtered_df = df.copy()

if selected_localities:
    filtered_df = filtered_df[filtered_df["location"].isin(selected_localities)]

if online_option != "All":
    filtered_df = filtered_df[filtered_df["online_order"] == online_option]

if table_option != "All":
    filtered_df = filtered_df[filtered_df["book_table"] == table_option]

# Include unrated rows if slider includes full lower range, else filter strictly
if min_rating > 1.0 or max_rating < 5.0:
    filtered_df = filtered_df[
        filtered_df["rating_num"].notnull() &
        (filtered_df["rating_num"] >= min_rating) &
        (filtered_df["rating_num"] <= max_rating)
    ]

# Cost filtering
filtered_df = filtered_df[
    filtered_df["approx_cost_num"].isnull() |
    ((filtered_df["approx_cost_num"] >= cost_range[0]) & (filtered_df["approx_cost_num"] <= cost_range[1]))
]

is_filtered = len(filtered_df) < len(df)

# Render Main Dashboard
render_header()

# KPI Metrics Section
total_records = len(filtered_df)
avg_rating_val = filtered_df["rating_num"].mean()
total_votes_val = int(filtered_df["votes_num"].sum())
avg_cost_val = filtered_df["approx_cost_num"].mean()
num_locs = filtered_df["location"].nunique()

render_metrics_cards(
    total_count=total_records,
    avg_rating=avg_rating_val,
    total_votes=total_votes_val,
    avg_cost=avg_cost_val,
    num_localities=num_locs,
    is_filtered=is_filtered
)

st.markdown("---")

if total_records == 0:
    st.warning("⚠️ No restaurants match the selected filter criteria. Please adjust your sidebar filters.")
    st.stop()

# Navigation Tabs
tab1, tab2, tab3, tab4, tab5 = st.tabs([
    "📊 Locality & Demand Analytics",
    "🥘 Cuisines & Advanced Heatmap",
    "💰 Pricing, Ratings & Services",
    "🔍 Data Quality & Spark Audit",
    "📥 Analytical Reports & Downloads"
])

with tab1:
    st.subheader("Geographic Restaurant Concentration & Rating Profiles")
    col1, col2 = st.columns([3, 2])

    with col1:
        if is_filtered:
            loc_summary_filtered = (
                filtered_df.groupby("location")
                .agg(
                    restaurant_count=("name", "count"),
                    avg_rating=("rating_num", "mean"),
                    avg_approx_cost=("approx_cost_num", "mean"),
                    total_votes=("votes_num", "sum")
                )
                .reset_index()
                .sort_values("restaurant_count", ascending=False)
            )
            render_locality_chart(loc_summary_filtered)
        else:
            render_locality_chart(locality_agg)

    with col2:
        render_rating_distribution_chart(filtered_df)

    st.markdown("---")
    st.markdown(
        """
        **Geospatial Implementation Note:**  
        The raw dataset provides textual locality and street addresses, but does *not* contain latitude/longitude coordinates.  
        Following academic integrity requirements, no fictitious coordinates have been fabricated. Spatial density is represented 
        via granular commercial locality aggregations and regional concentration indices.
        """
    )

with tab2:
    st.subheader("Cuisine Landscape and Advanced Bivariate Heatmap")
    st.markdown(
        """
        This section addresses **Unit 4: Visualization Techniques for Big Data - Heatmaps and High-Dimensional Cross-Tabulations**.  
        The matrix visualizes the joint distribution of restaurants across the top commercial zones and predominant culinary styles.
        """
    )

    if not matrix_agg.empty:
        render_cuisine_matrix_chart(matrix_agg)
    else:
        st.info("Locality-cuisine matrix is available in overall summary mode.")

    c1, c2 = st.columns(2)
    with c1:
        st.markdown("#### 🏆 Most Frequent Cuisines in Bangalore")
        if not cuisine_agg.empty:
            st.dataframe(
                cuisine_agg.head(10)[["cuisine_item", "restaurant_count", "avg_rating", "avg_approx_cost"]]
                .rename(columns={
                    "cuisine_item": "Cuisine",
                    "restaurant_count": "Total Outlets",
                    "avg_rating": "Avg Rating",
                    "avg_approx_cost": "Avg Cost (₹)"
                }),
                use_container_width=True
            )
    with c2:
        st.markdown("#### ⭐ Highest Rated Cuisines (Min. 30 Outlets)")
        if not cuisine_rated_agg.empty:
            st.dataframe(
                cuisine_rated_agg.head(10)[["cuisine_item", "restaurant_count", "avg_rating", "total_votes"]]
                .rename(columns={
                    "cuisine_item": "Cuisine",
                    "restaurant_count": "Sample Outlets",
                    "avg_rating": "Avg Rating",
                    "total_votes": "Total Votes"
                }),
                use_container_width=True
            )

with tab3:
    st.subheader("Price-to-Rating Relationships and Feature Availability Impact")
    col1, col2 = st.columns([3, 2])

    with col1:
        render_cost_rating_scatter(filtered_df)

    with col2:
        st.markdown("#### 📈 Statistical Correlation Metrics")
        corr_path = ANALYSIS_RESULTS_DIR / "correlations.json"
        if corr_path.exists():
            with open(corr_path) as f:
                corrs = json.load(f)
            st.write(
                f"""
                - **Approximate Cost vs. Rating Correlation:** `{corrs.get('corr_cost_rating', 'N/A')}` (Weak-Moderate positive association)
                - **Customer Votes vs. Rating Correlation:** `{corrs.get('corr_votes_rating', 'N/A')}` (Moderate positive association)
                - **Approximate Cost vs. Customer Votes:** `{corrs.get('corr_cost_votes', 'N/A')}` (Moderate positive association)
                """
            )
        st.info(
            "💡 **Correlation vs. Causation Principle:** A higher approximate cost is moderately associated with higher customer ratings (r ≈ +0.33), but this does not prove that premium pricing causes high ratings. Quality ingredients, service standards, and brand reputation act as latent confounding variables."
        )

with tab4:
    st.subheader("Apache Spark Data Cleaning & Data Quality Audit")
    if not quality_df.empty:
        q = quality_df.iloc[0]
        c1, c2, c3, c4 = st.columns(4)
        c1.metric("Raw Dataset Rows", f"{int(q['initial_raw_rows']):,}")
        c2.metric("Duplicate Listings Removed", f"{int(q['duplicate_rows_removed']):,}")
        c3.metric("Cleaned Unique Restaurants", f"{int(q['final_cleaned_rows']):,}")
        c4.metric("Valid Ratings Proportion", f"{q['ratings_completeness_pct']}%")

        st.markdown("#### Detailed Data Quality Audit Log")
        st.dataframe(quality_df, use_container_width=True)

    st.markdown(
        """
        ### Data Preprocessing & Cleaning Rules Implemented in PySpark:
        1. **Rating String Normalization:** Extracted numeric values from raw strings like `'4.1/5'`. Crucially, sentinel indicators (`'NEW'`, `'-'`) and unrated entries were transformed into PySpark `null` rather than `0.0` to preserve the true shape of the rating distribution.
        2. **Thousand Separator Removal:** Extracted numbers from `'approx_cost(for two people)'` by stripping embedded commas (`','`) and whitespace before casting to `DoubleType`.
        3. **Entity Deduplication:** Resolved multi-zone duplicate listings (`listed_in(city)`) by deduplicating on primary physical identity `[name, address, location]`, reducing 51,717 raw entries to 12,519 true unique dining establishments.
        """
    )

with tab5:
    st.subheader("Academic Reports, Key Insights, and Download Center")

    st.markdown(
        """
        ### 📌 Key Strategic Insights:
        1. **Local Spatial Clustering:** Whitefield (887), Electronic City (730), and BTM (729) represent the highest density of dining establishments in Bangalore, aligning directly with major IT business corridors and student clusters.
        2. **Cuisine Market Saturation:** North Indian (5,050 outlets) and Chinese (3,600 outlets) dominate total market availability. However, high-frequency cuisines do not automatically have the highest ratings; specialty categories with thresholded sample sizes demonstrate significantly higher customer satisfaction.
        3. **Impact of Delivery Enablement:** Restaurants offering online ordering show significantly higher total customer review volume and engagement than offline-only outlets.
        """
    )

    st.markdown("---")
    st.markdown("#### 📥 Download Processed Datasets & Spark Results")

    d1, d2, d3 = st.columns(3)
    with d1:
        st.download_button(
            label="Download Cleaned Dataset (CSV)",
            data=filtered_df.to_csv(index=False).encode("utf-8"),
            file_name="zomato_bangalore_cleaned_sample.csv",
            mime="text/csv"
        )
    with d2:
        if not locality_agg.empty:
            st.download_button(
                label="Download Locality Summary (CSV)",
                data=locality_agg.to_csv(index=False).encode("utf-8"),
                file_name="locality_summary_spark.csv",
                mime="text/csv"
            )
    with d3:
        if not cuisine_agg.empty:
            st.download_button(
                label="Download Cuisine Ranking (CSV)",
                data=cuisine_agg.to_csv(index=False).encode("utf-8"),
                file_name="cuisine_popularity_spark.csv",
                mime="text/csv"
            )
